import { mkdir, rm, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { isAbsolute, join, relative } from 'node:path';
import type { FoundComponent } from './components';
import type { Problem } from './types';
import { exists, type AngularApp } from './workspace';

/** Where verify writes its harness and output, ignored by git. */
export const VERIFY_DIR = '.ndop/verify';

/** Options SSR adds, which the harness, a browser-only page, drops. */
const SERVER_OPTIONS = [
  'server',
  'ssr',
  'prerender',
  'outputMode',
  'appShell',
  'serviceWorker',
];

/** The outcome of building the harness. */
export interface HarnessBuild {
  /** Whether it built. */
  ok: boolean;
  /** Absolute folder of the built page, when it built. */
  output?: string;
  /** Type and template errors, mapped to files. */
  problems: Problem[];
}

/**
 * The harness entry point: a page that renders one of the checked
 * components, picked by `?c=<ClassName>`, with the app's own providers.
 *
 * @param app - The application.
 * @param components - Components to make renderable.
 * @param appConfig - Project-relative `app.config.ts`, if the app has one.
 * @returns The entry's source.
 */
export function harnessSource(
  app: AngularApp,
  components: readonly FoundComponent[],
  appConfig: string | undefined,
): string {
  const specifier = (file: string) =>
    relative(join(app.root, VERIFY_DIR), join(app.root, file))
      .replace(/\\/g, '/')
      .replace(/\.ts$/, '');
  const imports = components.map(
    (component, index) =>
      `import { ${component.name} as Component${index} } from '${specifier(component.file)}';`,
  );
  const entries = components.map(
    (component, index) =>
      `  ${JSON.stringify(component.name)}: Component${index},`,
  );
  return `// Generated by ndop verify; deleted and rewritten on every run.
import { Component, type ApplicationConfig, type Type } from '@angular/core';
import { NgComponentOutlet } from '@angular/common';
import { bootstrapApplication } from '@angular/platform-browser';
${appConfig ? `import { appConfig } from '${specifier(appConfig)}';` : 'const appConfig: ApplicationConfig = { providers: [] };'}
${imports.join('\n')}

const components: Record<string, Type<unknown>> = {
${entries.join('\n')}
};
const name = new URLSearchParams(location.search).get('c') ?? '';

@Component({
  selector: 'ndop-verify',
  imports: [NgComponentOutlet],
  template: '<ng-container *ngComponentOutlet="component" />',
})
class Harness {
  protected readonly component = components[name] ?? null;
}

bootstrapApplication(Harness, appConfig).catch((error: unknown) => console.error(error));
`;
}

/**
 * Builds the harness through the app's own `build` target with Angular's
 * Architect (ADR-0018), so it compiles with the app's Angular version,
 * styles, aliases and strict template checks; that build is verify's
 * type-check. SSR options are dropped, so the harness is a plain browser
 * page; the app's own files are never changed.
 *
 * @param app - The application.
 * @param components - Components to render.
 * @returns The build's outcome and its errors.
 */
export async function buildHarness(
  app: AngularApp,
  components: readonly FoundComponent[],
): Promise<HarnessBuild> {
  const folder = join(app.root, VERIFY_DIR);
  await rm(join(folder, 'dist'), { recursive: true, force: true });
  await mkdir(folder, { recursive: true });
  const appConfigPath = join(app.sourceRoot, 'app/app.config.ts');
  const appConfig = (await exists(join(app.root, appConfigPath)))
    ? appConfigPath
    : undefined;
  await writeFile(
    join(folder, 'main.ts'),
    harnessSource(app, components, appConfig),
  );
  await writeFile(
    join(folder, 'index.html'),
    '<!doctype html>\n<html lang="en">\n  <head>\n    <meta charset="utf-8" />\n    <title>ndop verify</title>\n    <base href="/" />\n  </head>\n  <body>\n    <ndop-verify></ndop-verify>\n  </body>\n</html>\n',
  );

  const fromBuild = createRequire(
    createRequire(join(app.root, 'package.json')).resolve(
      '@angular/build/package.json',
    ),
  );
  const { Architect } = fromBuild(
    '@angular-devkit/architect',
  ) as typeof import('@angular-devkit/architect');
  const { WorkspaceNodeModulesArchitectHost } = fromBuild(
    '@angular-devkit/architect/node',
  ) as typeof import('@angular-devkit/architect/node');
  const fromArchitect = createRequire(
    fromBuild.resolve('@angular-devkit/architect'),
  );
  const { schema, workspaces, logging } = fromArchitect(
    '@angular-devkit/core',
  ) as typeof import('@angular-devkit/core');
  const { NodeJsSyncHost } = fromArchitect(
    '@angular-devkit/core/node',
  ) as typeof import('@angular-devkit/core/node');

  const { workspace } = await workspaces.readWorkspace(
    app.root,
    workspaces.createWorkspaceHost(new NodeJsSyncHost()),
  );
  const targetOf = (project: string, target: string) => {
    const found = workspace.projects.get(project)?.targets.get(target);
    if (!found)
      throw new Error(`angular.json has no ${project}:${target} target.`);
    return found;
  };
  const withoutServer = (options: Record<string, unknown> | undefined) =>
    Object.fromEntries(
      Object.entries(options ?? {}).filter(
        ([key]) => !SERVER_OPTIONS.includes(key),
      ),
    );
  const host = new WorkspaceNodeModulesArchitectHost(
    {
      getBuilderName: async (project, target) =>
        targetOf(project, target).builder,
      getMetadata: async (project) => {
        const definition = workspace.projects.get(project);
        return {
          root: definition?.root ?? '',
          ...(definition?.sourceRoot
            ? { sourceRoot: definition.sourceRoot }
            : {}),
          ...(definition?.prefix ? { prefix: definition.prefix } : {}),
          ...definition?.extensions,
        } as never;
      },
      getOptions: async (project, target, configuration) => {
        const found = targetOf(project, target);
        return withoutServer(
          configuration ? found.configurations?.[configuration] : found.options,
        ) as never;
      },
      hasTarget: async (project, target) =>
        workspace.projects.get(project)?.targets.has(target) ?? false,
      getDefaultConfigurationName: async (project, target) =>
        targetOf(project, target).defaultConfiguration,
    },
    app.root,
  );
  const registry = new schema.CoreSchemaRegistry();
  registry.addPostTransform(schema.transforms.addUndefinedDefaults);
  const architect = new Architect(host, registry);
  const logger = new logging.Logger('ndop-verify');
  const messages: string[] = [];
  logger.subscribe((entry) => messages.push(entry.message));

  const tsConfig = join(VERIFY_DIR, 'tsconfig.json');
  const appTsConfig = String(
    targetOf(app.project, 'build').options?.['tsConfig'] ?? 'tsconfig.app.json',
  );
  await writeFile(
    join(app.root, tsConfig),
    `${JSON.stringify({ extends: relative(folder, join(app.root, appTsConfig)), include: [], files: ['main.ts'] }, null, 2)}\n`,
  );
  const configurations = targetOf(app.project, 'build').configurations ?? {};
  const run = await architect.scheduleTarget(
    {
      project: app.project,
      target: 'build',
      ...('development' in configurations
        ? { configuration: 'development' }
        : {}),
    },
    {
      browser: join(VERIFY_DIR, 'main.ts'),
      index: join(VERIFY_DIR, 'index.html'),
      tsConfig,
      outputPath: join(VERIFY_DIR, 'dist'),
      progress: false,
    },
    { logger },
  );
  const result = await run.lastOutput;
  await run.stop();
  return {
    ok: result.success,
    ...(result.success ? { output: join(folder, 'dist/browser') } : {}),
    problems: buildProblems(
      messages.join('\n'),
      app.root,
      result.success,
      components.map((component) => component.file),
    ),
  };
}

/**
 * Turns the builder's esbuild-style messages into problems: every error,
 * and warnings about the checked files only, since the app's own warnings
 * aren't the checked code's. A failed build with no error that names a
 * file still gets one problem, carrying the log.
 *
 * @param output - Everything the build logged.
 * @param root - Workspace root; message paths are relative to it.
 * @param success - Whether the build succeeded.
 * @param checked - Project-relative paths of the checked files.
 * @returns The problems.
 */
export function buildProblems(
  output: string,
  root: string,
  success: boolean,
  checked: readonly string[],
): Problem[] {
  const problems: Problem[] = [];
  const pattern =
    /[✘▲] \[(ERROR|WARNING)\] (?:(TS\d+|NG\d+): )?([\s\S]+?)(?: \[plugin [^\]]+\])?\n\n\s+(\S+?):(\d+):(\d+):/g;
  for (const match of output.matchAll(pattern)) {
    const [, level, code, message = '', file = '', line = '1', column = '0'] =
      match;
    const path = isAbsolute(file) ? relative(root, file) : file;
    if (level === 'WARNING' && !checked.includes(path)) continue;
    problems.push({
      file: path,
      line: Number(line),
      column: Number(column) + 1,
      rule: `build/${code ?? 'esbuild'}`,
      severity: level === 'ERROR' ? 'error' : 'warning',
      message: message.replace(/\s*\n\s*/g, ' ').trim(),
    });
  }
  if (!success && !problems.some((problem) => problem.severity === 'error')) {
    problems.push({
      file: 'angular.json',
      line: 1,
      column: 1,
      rule: 'build/failed',
      severity: 'error',
      message: output.trim().split('\n').slice(-20).join('\n'),
    });
  }
  return problems;
}
