import { formatFiles, readJson, type Tree } from '@nx/devkit';
import {
  deriveCatalog,
  type CatalogMetadata,
} from '@ndop/eslint-plugin/catalog';
import type { EslintCatalogGeneratorSchema } from './schema';

/** Where the generated catalog lives. */
export const CATALOG_FILE =
  'packages/eslint-plugin/src/lib/catalog.generated.ts';

/**
 * The catalog module's text.
 *
 * @param tree - The workspace.
 * @param options - Where the built registry and primitives are.
 * @returns The TypeScript source, before formatting.
 * @throws When the registry or the primitives haven't been built.
 */
export function catalogSource(
  tree: Tree,
  options: EslintCatalogGeneratorSchema = {},
): string {
  const registry = options.registry ?? 'dist/registry/r';
  const primitives =
    options.primitives ?? 'dist/packages/primitives/package.json';
  const folder = `${registry}/metadata`;
  if (!tree.exists(folder) || !tree.exists(primitives)) {
    throw new Error(
      `Build the registry and the primitives first: ${folder} or ${primitives} is missing.`,
    );
  }
  const metadata = tree
    .children(folder)
    .filter((file) => file.endsWith('.json'))
    .sort()
    .map((file) => readJson<CatalogMetadata>(tree, `${folder}/${file}`));
  const exports = Object.keys(
    readJson<{ exports?: Record<string, unknown> }>(tree, primitives).exports ??
      {},
  );
  return `// Generated by \`nx g @ndop/workspace-plugin:eslint-catalog\` from the
// built registry's metadata (ADR-0018); its test fails when it's stale.
import type { Catalog } from './catalog';

/** What the rules know about Ndop's components. */
export const CATALOG: Catalog = ${JSON.stringify(deriveCatalog(metadata, exports), null, 2)};
`;
}

/**
 * Regenerates `@ndop/eslint-plugin`'s catalog (ADR-0018): which parts are
 * buttons, form controls and titled dialogs, and which `@ndop/primitives`
 * entry points are public, from the built registry's metadata and the
 * built primitives' exports.
 *
 * @param tree - The workspace.
 * @param options - Where the built registry and primitives are.
 *
 * @example
 * ```sh
 * pnpm nx run-many -t build -p registry primitives
 * pnpm nx g @ndop/workspace-plugin:eslint-catalog
 * ```
 */
export async function eslintCatalogGenerator(
  tree: Tree,
  options: EslintCatalogGeneratorSchema,
): Promise<void> {
  tree.write(CATALOG_FILE, catalogSource(tree, options));
  await formatFiles(tree);
}

export default eslintCatalogGenerator;
